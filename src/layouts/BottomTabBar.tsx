export function BottomTabBar() {
  const { theme } = useTheme()
  const isDark = theme === 'dark'

  return (
    <nav
      className={`fixed bottom-0 left-0 right-0 z-50 md:hidden shadow-tab-bar pb-safe border-t ${isDark ? 'bg-navy-950 border-navy-800' : 'bg-white border-slate-100'}`}
      aria-label="Mobile navigation"
    >
      <div className="flex items-stretch h-16">
        {tabs.map((tab) => (
          <NavLink
            key={tab.to}
            to={tab.to}
            end={tab.to === '/citizen'}
            className={({ isActive }) =>
              [
                'flex-1 flex flex-col items-center justify-center gap-0.5 transition-colors duration-200',
                isActive 
                    ? (isDark ? 'text-primary-400' : 'text-primary') 
                    : (isDark ? 'text-slate-500 hover:text-slate-300' : 'text-slate-400 hover:text-slate-600'),
              ].join(' ')
            }
            aria-label={tab.label}
          >
            {({ isActive }) => (
              <>
                <span className="relative">
                  {isActive ? tab.activeIcon : tab.icon}
                  {/* Report tab FAB-like highlight */}
                  {tab.label === 'Report' && (
                    <span
                      className="absolute inset-0 -m-1 rounded-full bg-primary/10"
                      aria-hidden="true"
                    />
                  )}
                </span>
                <span
                  className={[
                    'text-[10px] font-medium',
                    isActive ? 'text-primary' : 'text-slate-400',
                  ].join(' ')}
                >
                  {tab.label}
                </span>
              </>
            )}
          </NavLink>
        ))}
      </div>
    </nav>
  )
}
